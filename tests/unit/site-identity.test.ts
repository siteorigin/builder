const node = (g: SeoGraph, id: string) => g['@graph'].find((n) => n['@id'] === id) as GraphNode;

/** Every `@id` a node's properties refer to or describe. */
function idsIn(value: unknown): string[] {
  if (Array.isArray(value)) return value.flatMap(idsIn);
  if (!value || typeof value !== 'object') return [];
  return Object.entries(value).flatMap(([k, v]) => (k === '@id' && typeof v === 'string' ? [v] : idsIn(v)));
}

/** One graph whose IDs are each used once, and whose every reference to the site's own addresses names one of its nodes. */
function expectConnected(g: SeoGraph) {
  const ids = g['@graph'].map((n) => n['@id']);
  expect(new Set(ids).size, 'IDs are used once').toBe(ids.length);
  for (const n of g['@graph'])
    for (const id of idsIn(Object.fromEntries(Object.entries(n).filter(([k]) => k !== '@id'))))
      if (id.startsWith(ROOT)) expect(ids, `${n['@id']} → ${id}`).toContain(id);
  const [publisher, website, webpage, breadcrumb] = g['@graph'];
  expect(website.publisher).toEqual({ '@id': publisher['@id'] });
  expect(webpage.isPartOf).toEqual({ '@id': website['@id'] });
  expect(webpage.breadcrumb).toEqual({ '@id': breadcrumb['@id'] });
}

/** The structured data scripts of each page and entry file the website has, by the document it was made from. */
function graphsByDocument(files: Map<string, string>): Map<string, SeoGraph[]> {
  const out = new Map<string, SeoGraph[]>();
  for (const [path, content] of files) {
    const source = /^<!-- Generated by SiteOrigin Builder from (siteorigin\/(?:pages|collections)\/[^ ]+\.json)\./.exec(content)?.[1];
    if (!path.endsWith('+page.svelte') || !source) continue;
    const scripts = [...content.matchAll(/\{@html ("(?:[^"\\]|\\.)*")\}/g)]
      .map((m) => JSON.parse(m[1]) as string)
      .filter((html) => html.startsWith('<script type="application/ld+json">'))
      .map((html) => JSON.parse(html.replace(/^<script type="application\/ld\+json">|<\/script>$/g, '')) as SeoGraph);
    out.set(source, scripts);
  }
  return out;
}

