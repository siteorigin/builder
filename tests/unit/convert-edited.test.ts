describe('a design’s file moved to the custom folder (#737)', () => {
  it('rewrites only the references that would lead elsewhere from there, inside their quotes', async () => {
    const source = [
      '<!-- Generated by SiteOrigin Builder from siteorigin/components/x/component.json. -->',
      '<script>',
      "\timport Card from './card.svelte';",
      '\timport { has } from "../runtime/util.js";',
      "\timport Own from '../custom/Own.svelte';",
      "\timport { page } from '$app/state';",
      "\timport lib from '$lib/helpers.js';",
      "\texport { thing } from './thing.js';",
      "\tconst lazy = () => import('./lazy.svelte');",
      '\tconst tpl = () => import(`./tpl.js`);',
      "\tconst icon = new URL('./icon.svg', import.meta.url).href;",
      "\tconst text = './not-a-module.svelte';",
      '</script>',
      '',
      '<a href="./about">About</a>',
      '<Card />',
      '',
      '<style>',
      "\t@import './theme.css';",
      '\t.a { background: url(./bg.png); }',
      "\t.b { background: url('../styles/x.png'); }",
      '</style>',
      ''
    ].join('\r\n');
    const out = await relocateSource(source, FROM, TO);
    expect(out).toBe(
      source
        .replace("'./card.svelte'", "'../generated/card.svelte'")
        .replace("'./thing.js'", "'../generated/thing.js'")
        .replace("'./lazy.svelte'", "'../generated/lazy.svelte'")
        .replace('`./tpl.js`', '`../generated/tpl.js`')
        .replace("'./icon.svg'", "'../generated/icon.svg'")
        .replace("'./theme.css'", "'../generated/theme.css'")
        .replace('url(./bg.png)', 'url(../generated/bg.png)')
    );
    // Line endings, the header note, a link and a plain string are as they were.
    expect(out).toContain('\r\n');
    expect(out).toContain("const text = './not-a-module.svelte';");
    expect(out).toContain('<a href="./about">');
  });

  it('follows escaped paths, queries, bare style URLs and a form’s copy for AI agents, and leaves words alone', async () => {
    const source = [
      '<script>',
      '\timport A from ".\\x2fa.js";',
      "\timport icon from './icon.svg?url#frag';",
      "\timport Form from './contact-form.webmcp.svelte';",
      "\timport Lib from '$lib/siteorigin/generated/contact-form.webmcp.svelte';",
      "\tconst pic = new URL('pic.png', import.meta.url);",
      '</script>',
      '',
      '<style>',
      '\t/* url(./comment.png) */',
      '\t.a::after { content: "url(./literal.png)"; }',
      '\t.b { background: URL("./has space.png"); }',
      '\t.c { background: url(bare.png); }',
      '\t.d { background: url(/root.png), url(data:image/png;base64,AA==); }',
      '\t.e::before { content: url(./badge.svg); --caption: "url(cap.svg)"; }',
      '\t.f { background: url(.well-known/logo.svg); }',
      '\t@import /* note */ "./note.css";',
      '</style>',
      ''
    ].join('\n');
    const redirect = (target: string) => (target === 'src/lib/siteorigin/generated/contact-form.webmcp.svelte' ? 'src/lib/siteorigin/generated/contact-form.svelte' : undefined);
    expect(await relocateSource(source, FROM, TO, redirect)).toBe(
      source
        .replace('".\\x2fa.js"', '"../generated/a.js"')
        .replace("'./icon.svg?url#frag'", "'../generated/icon.svg?url#frag'")
        .replace("'./contact-form.webmcp.svelte'", "'../generated/contact-form.svelte'")
        .replace("'$lib/siteorigin/generated/contact-form.webmcp.svelte'", "'$lib/siteorigin/generated/contact-form.svelte'")
        .replace("'pic.png'", "'../generated/pic.png'")
        .replace('URL("./has space.png")', 'URL("../generated/has space.png")')
        .replace('url(bare.png)', 'url(../generated/bare.png)')
        .replace('url(./badge.svg)', 'url(../generated/badge.svg)')
        .replace('url(.well-known/logo.svg)', 'url(../generated/.well-known/logo.svg)')
        .replace('"./note.css"', '"../generated/note.css"')
    );
  });

  it('reads a file as code only when its bytes are text that reads back exactly', () => {
    expect(textOfBytes(Buffer.from('\uFEFF<p>a</p>\r\n'))).toBe('\uFEFF<p>a</p>\r\n');
    expect(textOfBytes(Buffer.from([0x3c, 0x70, 0x00, 0x3e]))).toBeNull();
    expect(textOfBytes(Buffer.from([0x3c, 0x70, 0xff, 0x3e]))).toBeNull();
  });

  it('leaves code that does not parse, or that needs no change, exactly as it is', async () => {
    const broken = "<script>\n\timport A from './a.svelte';\n\tlet x = ;\n</script>\n";
    expect(await relocateSource(broken, FROM, TO)).toBe(broken);
    const settled = "<script>\n\timport { has } from '../runtime/util.js';\n</script>\n<p>{has(1)}</p>\n";
    expect(await relocateSource(settled, FROM, TO)).toBe(settled);
  });
});

describe('placements of a converted design file (#737)', () => {
  /**
   * The starter's hero placed with its own choices (an axis, an entrance, an anchor, a part's styles), then its file
   * converted unchanged: the site is generated as it was, but for which file the placements import.
   */
  function converted(keepLink = true) {
    const state = createStarterState('business', 'Convert', false);
    const hero = 'foundation.hero.split';
    const [{ node }] = instancesOf(state, hero) as Array<{ node: InstanceNode }>;
    node.variants = { ...node.variants, tone: 'inverse' };
    node.appear = 'lift';
    node.anchor = 'welcome';
    node.overrides = { heading: { base: { color: '#aa0000' } }, root: { base: { paddingTop: '48px' } } };
    // A list's single item styled on its own, when the starter has a design with one.
    const listed = Object.values(state.components).find((d) => d.kind === 'managed' && Object.keys(d.parts).some((p) => repeatedPartList(d, p)) && instancesOf(state, d.id).some((u) => u.owner.kind === 'page'));
    if (listed) {
      const part = Object.keys(listed.parts).find((p) => repeatedPartList(listed, p))!;
      const list = repeatedPartList(listed, part)!;
      const placed = instancesOf(state, listed.id).find((u) => u.owner.kind === 'page')!.node;
      const items = (placed.props[list] ?? listed.properties[list].default) as Array<{ id: string }>;
      placed.itemOverrides = { [part]: { list, items: { [items[0].id]: { base: { color: '#00aa00' } } } } };
    }
    const before = generateProject(state, { instrument: false });
    const after = structuredClone(state) as ProjectState;
    const ids: Record<string, string> = {};
    for (const d of [state.components[hero], ...(listed ? [listed] : [])]) {
      const made = convertEditedDesign(after, d.id, before.get(defFile(d))!);
      if (!keepLink) delete after.components[made.definitionId].generatedFrom;
      ids[d.id] = made.definitionId;
    }
    return { state, after, before, ids, hero, listed };
  }
  /**
   * A generated file with each converted design's file and its code's file named alike (path and import name), and
   * its imports in one order: what is left is everything else the file says.
   */
  const asDesigns = (text: string, after: ProjectState, ids: Record<string, string>) => {
    let out = text;
    const ident = (id: string) => new RegExp(`\\bC_${id.replace(/[^a-zA-Z0-9]+/g, '_')}_[a-z0-9]+\\b`, 'g');
    for (const [design, code] of Object.entries(ids)) {
      const file = after.components[code].sourcePath!.split('/').pop()!;
      const designFile = defFile(after.components[design]).split('/').pop()!;
      out = out.replaceAll(`custom/${file}`, `generated/${designFile}`).replace(ident(code), `C_${design}`).replace(ident(design), `C_${design}`);
    }
    const lines = out.split('\n');
    const imports = lines.filter((l) => /^\timport /.test(l)).sort();
    let i = 0;
    return lines.map((l) => (/^\timport /.test(l) ? imports[i++] : l)).join('\n');
  };

  it('gives each placement what it gave the design’s file, and styles it with the design’s rules', () => {
    const { after, before, ids, hero, listed } = converted();
    expect(instancesOf(after, hero)).toEqual([]);
    // A list item styled on its own is part of what is compared.
    expect(listed).toBeDefined();
    expect(before.get('src/routes/+page.svelte')).toContain('so_oi=');
    const now = generateProject(after, { instrument: false });
    for (const [path, text] of before) {
      // Pages, layouts and stylesheets: the same, but for the file imported.
      if (!/^src\/routes\/|^src\/lib\/siteorigin\/styles\//.test(path)) continue;
      expect(asDesigns(now.get(path) ?? '', after, ids), path).toBe(asDesigns(text, after, ids));
    }
    // The converted placement keeps its anchor and its entrance as the design's file took them.
    const home = now.get('src/routes/+page.svelte')!;
    expect(home).toContain('"welcome"');
    expect(home).toMatch(/so_appear=\{?"lift"\}?/);
    expect(home).not.toMatch(/\bvariant=/);
  });

  it('generates a design edited to place its own copy without going round forever', () => {
    const { after, ids, hero } = converted();
    const design = after.components[hero];
    const root = design.tree!.rootIds[0];
    const loop: InstanceNode = { id: 'n_loop1', kind: 'instance', definitionId: ids[hero], props: {} };
    // First, so every walk of the design meets it before anything that would end the walk early (its image).
    design.tree!.nodes = { [loop.id]: loop, ...design.tree!.nodes };
    const parent = design.tree!.nodes[root] as { children?: string[] };
    parent.children = [...(parent.children ?? []), loop.id];
    expect(() => generateProject(after, { instrument: false })).not.toThrow();
  });

  it('counts a placement’s own entrance however the code reads it, when it is the only one on the site', () => {
    const state = createStarterState('business', 'Convert', false);
    for (const { tree } of allTrees(state)) for (const n of Object.values(tree.nodes)) if ('appear' in n) delete (n as { appear?: unknown }).appear;
    const hero = 'foundation.hero.split';
    const [{ node }] = instancesOf(state, hero) as Array<{ node: InstanceNode }>;
    node.appear = 'lift';
    expect(usesAppear(state)).toBe(true);
    // Nothing in the code says on its own that it shows an entrance: it hands what it is given to its root.
    convertEditedDesign(state, hero, '<script>\n\tlet { so_appear } = $props();\n</script>\n\n<section {...(so_appear ? { "data-appear": so_appear } : {})}>Hero</section>\n');
    expect(usesAppear(state)).toBe(true);
  });

  it('styles a part the code added, where it is placed inside a design, as any code component’s', () => {
    const { after, ids, hero } = converted();
    const code = after.components[ids[hero]];
    code.parts.badge = { nodeId: 'badge', label: 'Badge' };
    const { state: next, results } = applyOperations(after, [{ type: 'component.create', name: 'Landing block' }]);
    const design = next.components[results[0].definitionId as string];
    const { state: placed } = applyOperations(next, [{ type: 'node.insert', owner: { kind: 'component', id: design.id }, parentId: design.tree!.rootIds[0], definitionId: ids[hero] }]);
    const [{ node }] = instancesOf(placed, ids[hero]).filter((u) => u.owner.kind === 'component') as Array<{ node: InstanceNode }>;
    node.overrides = { badge: { base: { color: '#123456' } }, heading: { base: { color: '#654321' } } };
    const files = generateProject(placed, { instrument: false });
    const designFile = files.get(defFile(placed.components[design.id]))!;
    expect(designFile).toMatch(/so_o=\{\{[^}]*"badge":/);
    const css = files.get('src/lib/siteorigin/styles/components.css')!;
    expect(css).toContain('#123456');
    expect(css).toContain('#654321');
  });

  it('is called as code once it no longer names the design it was made from', () => {
    const { after, before, ids } = converted(false);
    const now = generateProject(after, { instrument: false });
    // Without the link it is called as any code component is: the first axis as `variant`, no entrance passed.
    expect(now.get('src/routes/+page.svelte')).toMatch(/\bvariant=/);
    expect(now.get('src/routes/+page.svelte')).not.toMatch(/so_appear=\{?"lift"/);
    expect(asDesigns(now.get('src/routes/+page.svelte')!, after, ids)).not.toBe(asDesigns(before.get('src/routes/+page.svelte')!, after, ids));
  });
});

describe('the code a design’s file becomes (#737)', () => {
  it('keeps the design’s contract, so a slot that takes the design takes it too', () => {
    const state = createStarterState('business', 'Convert', false);
    const hero = state.components['foundation.hero.split'];
    const made = convertEditedDesign(state, hero.id, '<p>edited</p>\n');
    const code = state.components[made.definitionId];
    expect(code).toMatchObject({ kind: 'code', owner: 'project', componentId: hero.componentId, category: hero.category, generatedFrom: hero.id });
    expect(takesComponent({ label: 'Hero', componentIds: [hero.id] }, code)).toBe(true);
    expect(takesComponent({ label: 'Hero', componentIds: [hero.componentId] }, code)).toBe(true);
    expect(takesComponent({ label: 'Other', componentIds: ['foundation.cta.banner'] }, code)).toBe(false);
    // The variant names, and what each option says of itself, are kept; their styles stay the design's.
    for (const [axis, a] of Object.entries(hero.variantAxes ?? {}))
      for (const [option, o] of Object.entries(a.options)) {
        const { styles: _styles, ...rest } = o;
        expect(code.variantAxes?.[axis]?.options[option]).toEqual(rest);
      }
  });
});

