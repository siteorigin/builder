/**
 * Builds `scripts/sync-sources.mjs`, the sync an exported project runs with `npm run sync` (#680): this app's own
 * sync (src/main/sources/standalone.ts) in one ES module that needs only Node, with every package it uses inside it.
 * The main process's build ships it beside the app (electron.vite.config.ts), and the export copies it out; tests
 * build it the same way.
 */
import { build } from 'esbuild';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ThemePack } from '@catalogue/pack';
import { loadPacks } from '../src/main/packs/loader';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** What the script's first lines say: whose it is, and that an export writes it again. */
export const SYNC_CLI_BANNER = [
  '// Generated by SiteOrigin Builder. Do not edit: exporting the project again writes it again.',
  "// Syncs this project's external sources into siteorigin/collections/ and static/assets/: npm run sync.",
  '// SiteOrigin Builder is licensed under the Apache License 2.0. The notices of the packages bundled in it are at the end.'
].join('\n');

/**
 * The themes the script checks a sync against (registerSyncPacks in standalone.ts): the releases the app ships, loaded
 * as the app loads them, with what a check reads of them (tokens, components, which fonts they have) and none of their
 * files, which the exported project does not have.
 */
export async function syncPacks(): Promise<ThemePack[]> {
  const { packs, refused } = await loadPacks([{ dir: resolve(root, 'resources', 'packs'), source: 'bundled' }]);
  if (refused.length || !packs.length) throw new Error(`The sync script needs the shipped theme releases: ${refused.map((r) => r.reason).join(' ') || 'there are none'}.`);
  return packs.map(({ pack: { previews: _previews, fonts, ...pack } }) => {
    void _previews;
    return { ...pack, fonts: fonts.map((f) => ({ ...f, notice: '', faces: [] })) };
  });
}

/** The script's text. */
export async function buildSyncCli(): Promise<string> {
  const out = await build({
    entryPoints: [resolve(root, 'src/main/sources/standalone-entry.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    minify: true,
    write: false,
    tsconfig: resolve(root, 'tsconfig.node.json'),
    // Nothing of the app's own build is read by the sync: a commit stamp, say, is never there.
    define: { __BUILD_COMMIT__: '""', __BUILD_DATE__: '""', __SYNC_PACKS__: JSON.stringify(await syncPacks()) },
    banner: { js: SYNC_CLI_BANNER },
    legalComments: 'none',
    metafile: true,
    logLevel: 'silent'
  });
  // Only Node's own modules are imported: anything else would need an install the exported project does not have.
  const foreign = Object.values(out.metafile.outputs).flatMap((o) => o.imports.filter((i) => i.external && !i.path.startsWith('node:')).map((i) => i.path));
  if (foreign.length) throw new Error(`The sync script would import ${[...new Set(foreign)].join(', ')}.`);
  // Each bundled package's own licence travels with the copy of it here.
  const packages = [...new Set(Object.keys(out.metafile.inputs).flatMap((p) => /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(p)?.[1] ?? []))].sort();
  const notices = packages.map((name) => {
    const dir = join(root, 'node_modules', name);
    const file = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license'].map((f) => join(dir, f)).find((f) => existsSync(f));
    if (!file) throw new Error(`${name} is bundled in the sync script but has no licence file.`);
    const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string };
    return `${name} ${version}\n\n${readFileSync(file, 'utf8').trim()}`;
  });
  return `${out.outputFiles[0].text}\n/*\n${notices.join('\n\n---\n\n').replace(/\*\//g, '* /')}\n*/\n`;
}
