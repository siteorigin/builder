/**
 * Builds `scripts/sync-sources.mjs`, the sync an exported project runs with `npm run sync` (#680): this app's own
 * sync (src/main/sources/standalone.ts) in one ES module that needs only Node, with every package it uses inside it.
 * The main process's build ships it beside the app (electron.vite.config.ts), and the export copies it out; tests
 * build it the same way.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
// By a relative path, not the `@catalogue` alias, which Electron's config load cannot resolve; pack.ts imports types only.
import { BUNDLED_PACK_IDS, type PackManifest, type ThemePack } from '../src/catalogue/pack';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** What the script's first lines say: whose it is, and that an export writes it again. */
export const SYNC_CLI_BANNER = [
  '// Generated by SiteOrigin Builder. Do not edit: exporting the project again writes it again.',
  "// Syncs this project's external sources into siteorigin/collections/ and static/assets/: npm run sync.",
  '// SiteOrigin Builder is licensed under the Apache License 2.0. The notices of the packages bundled in it are at the end.'
].join('\n');

/**
 * The themes the script checks a sync against (registerSyncPacks in standalone.ts): the releases the app ships, with
 * what a check reads of them (tokens, components, which fonts they have) and none of their files, which the exported
 * project does not have. Only Foundation ships (a project on a development fixture is checked against it). Read from
 * the committed manifests rather than through the app's loader, which this file cannot import: Electron's build loads
 * it from its config, before the app's module aliases exist. The build checks those releases against their lock
 * first (`npm run build:packs -- --committed`), and the unit tests load them as the app does.
 */
export function syncPacks(): ThemePack[] {
  const dir = resolve(root, 'resources', 'packs');
  // In the order the app ranks them (bundledOrder in src/main/packs/loader.ts), so the default theme is the app's.
  const rank = (id: string) => (BUNDLED_PACK_IDS.includes(id) ? BUNDLED_PACK_IDS.indexOf(id) : BUNDLED_PACK_IDS.length);
  const ids = readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .sort((a, b) => rank(a) - rank(b) || (a < b ? -1 : a > b ? 1 : 0));
  if (!ids.length) throw new Error(`The sync script needs the shipped theme releases, and ${dir} has none.`);
  return ids.map((id) => {
    const raw = readFileSync(join(dir, id, 'pack.json'));
    const { format: _format, schemaVersion: _schema, files: _files, previews: _previews, fonts, ...pack } = JSON.parse(raw.toString('utf8')) as PackManifest;
    void [_format, _schema, _files, _previews];
    return { ...pack, fonts: fonts.map((f) => ({ ...f, notice: '', faces: [] })), digest: createHash('sha256').update(raw).digest('hex'), source: 'bundled' as const };
  });
}

/** The script's text. */
export async function buildSyncCli(): Promise<string> {
  const out = await build({
    entryPoints: [resolve(root, 'src/main/sources/standalone-entry.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    minify: true,
    write: false,
    tsconfig: resolve(root, 'tsconfig.node.json'),
    // Nothing of the app's own build is read by the sync: a commit stamp, say, is never there.
    define: { __BUILD_COMMIT__: '""', __BUILD_DATE__: '""', __SYNC_PACKS__: JSON.stringify(syncPacks()) },
    banner: { js: SYNC_CLI_BANNER },
    legalComments: 'none',
    metafile: true,
    logLevel: 'silent'
  });
  // Only Node's own modules are imported: anything else would need an install the exported project does not have.
  const foreign = Object.values(out.metafile.outputs).flatMap((o) => o.imports.filter((i) => i.external && !i.path.startsWith('node:')).map((i) => i.path));
  if (foreign.length) throw new Error(`The sync script would import ${[...new Set(foreign)].join(', ')}.`);
  // Each bundled package's own licence travels with the copy of it here.
  const packages = [...new Set(Object.keys(out.metafile.inputs).flatMap((p) => /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(p)?.[1] ?? []))].sort();
  const notices = packages.map((name) => {
    const dir = join(root, 'node_modules', name);
    const file = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license'].map((f) => join(dir, f)).find((f) => existsSync(f));
    if (!file) throw new Error(`${name} is bundled in the sync script but has no licence file.`);
    const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string };
    return `${name} ${version}\n\n${readFileSync(file, 'utf8').trim()}`;
  });
  return `${out.outputFiles[0].text}\n/*\n${notices.join('\n\n---\n\n').replace(/\*\//g, '* /')}\n*/\n`;
}
