/**
 * Builds `scripts/sync-sources.mjs`, the sync an exported project runs with `npm run sync` (#680): this app's own
 * sync (src/main/sources/standalone.ts) in one ES module that needs only Node, with every package it uses inside it.
 * The main process's build ships it beside the app (electron.vite.config.ts), and the export copies it out; tests
 * build it the same way.
 */
import { build } from 'esbuild';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** What the script's first lines say: whose it is, and that an export writes it again. */
export const SYNC_CLI_BANNER = [
  '// Generated by SiteOrigin Builder. Do not edit: exporting the project again writes it again.',
  "// Syncs this project's external sources into siteorigin/collections/ and static/assets/: npm run sync.",
  '// SiteOrigin Builder is licensed under the Apache License 2.0. Bundled: acorn (MIT), zod (MIT).'
].join('\n');

/** The script's text. */
export async function buildSyncCli(): Promise<string> {
  const out = await build({
    entryPoints: [resolve(root, 'src/main/sources/standalone-entry.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    minify: true,
    write: false,
    tsconfig: resolve(root, 'tsconfig.node.json'),
    // Nothing of the app's own build is read by the sync: a commit stamp, say, is never there.
    define: { __BUILD_COMMIT__: '""', __BUILD_DATE__: '""' },
    banner: { js: SYNC_CLI_BANNER },
    legalComments: 'none',
    metafile: true,
    logLevel: 'silent'
  });
  // Only Node's own modules are imported: anything else would need an install the exported project does not have.
  const foreign = Object.values(out.metafile.outputs).flatMap((o) => o.imports.filter((i) => i.external && !i.path.startsWith('node:')).map((i) => i.path));
  if (foreign.length) throw new Error(`The sync script would import ${[...new Set(foreign)].join(', ')}.`);
  return out.outputFiles[0].text;
}
