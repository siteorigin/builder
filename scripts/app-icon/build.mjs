/**
 * Writes every packaged app icon file from the one drawing in src/shared/app-icon.ts. Run it after changing that
 * drawing, on a Mac with Xcode 26 or later, and commit what it writes:
 *
 *   node scripts/app-icon/build.mjs
 *
 * - build/AppIcon.icon and build/Assets.car: the macOS 26 icon (Icon Composer layers, compiled by actool). macOS
 *   draws it with Liquid Glass and its dark, clear and tinted looks; build/after-pack.cjs puts the catalog in the
 *   app. It is compiled here rather than in the release build so the build machines need no Xcode 26.
 * - build/icon.icns: the macOS icon for the disk image and earlier macOS, with the small sizes drawn for their size.
 * - build/icon.svg and build/icon.png: the same at 1024, on Apple's grid (the Dock icon in development, the README).
 * - build/icon.ico, build/icons/ and build/icon-flat.png: Windows, Linux (one PNG per size, for the hicolor theme) and
 *   the Linux window, which draw icons nearly edge to edge.
 * - relay/viewer/mark.svg: the live session viewer's mark and favicon.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { appIconLayers, appIconSvg, appMarkMarkup, detailFor, ICON_COLORS, MARK_VIEWBOX } from '../../src/shared/app-icon.ts';

const build = resolve(dirname(fileURLToPath(import.meta.url)), '../../build');
const written = [];
const write = (name, data) => {
  writeFileSync(join(build, name), data);
  written.push(join(build, name));
};
// Each size is drawn at that size, so the renderer's own anti-aliasing sets the edges (a downscale rings at 16 px).
const render = (frame, px) => sharp(Buffer.from(appIconSvg({ frame, detail: detailFor(px), shadow: px > 32, px })), { density: (72 * px) / 1024 }).resize(px, px).png({ compressionLevel: 9 }).toBuffer();

// macOS at 1024, as SVG (the drawing to look at) and PNG.
write('icon.svg', `<!-- Generated by scripts/app-icon/build.mjs from src/shared/app-icon.ts; edit that, not this. -->\n${appIconSvg({ frame: 'mac' })}\n`);
write('icon.png', await render('mac', 1024));
write('icon-flat.png', await render('flat', 1024));

// The live session viewer's mark and favicon, which it shows at 16-32 px: the app's own mark at that size.
{
  const file = join(build, '..', 'relay', 'viewer', 'mark.svg');
  writeFileSync(file, `<!-- The SiteOrigin Builder mark for the live session viewer and its favicon. Generated by scripts/app-icon/build.mjs from src/shared/app-icon.ts; edit that, not this. -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX}">${appMarkMarkup(24, 'mark')}</svg>\n`);
  written.push(file);
}

// Linux: one PNG per size the hicolor theme indexes (not 1024, which it does not, so menus would find nothing).
{
  const dir = join(build, 'icons');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir);
  for (const px of [16, 24, 32, 48, 64, 128, 256, 512]) writeFileSync(join(dir, `${px}x${px}.png`), await render('flat', px));
  written.push(dir);
}

// Windows: an .ico of PNGs, one per size Windows asks for at 100-250% scaling, so none is a resample.
{
  const sizes = [16, 20, 24, 30, 32, 36, 40, 48, 64, 256];
  const images = await Promise.all(sizes.map((px) => render('flat', px)));
  const header = Buffer.alloc(6 + 16 * sizes.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  sizes.forEach((px, i) => {
    const at = 6 + 16 * i;
    header.writeUInt8(px >= 256 ? 0 : px, at);
    header.writeUInt8(px >= 256 ? 0 : px, at + 1);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(images[i].length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += images[i].length;
  });
  write('icon.ico', Buffer.concat([header, ...images]));
}

// macOS 26: the Icon Composer document, and its compiled asset catalog.
{
  const dir = join(build, 'AppIcon.icon');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, 'Assets'), { recursive: true });
  for (const [name, svg] of Object.entries(appIconLayers())) writeFileSync(join(dir, 'Assets', `${name}.svg`), svg);
  // Addo on the document's own white fill, the same in the dark appearance: he is the brand mark, charcoal on white,
  // in every appearance. Its two-stop ramp starts at the top, so its floor is lighter than the PNGs' (which hold pure
  // white to 60%), to keep the tile as white behind Addo. The system draws the glass, the shadows and the tinted looks.
  const srgb = (hex) => `srgb:${[1, 3, 5].map((i) => (parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(5)).join(',')},1.00000`;
  const doc = {
    'fill-specializations': [
      { value: { 'linear-gradient': [srgb(ICON_COLORS.white), srgb('#F2F4F7')] } },
      { appearance: 'dark', value: { 'linear-gradient': [srgb(ICON_COLORS.white), srgb('#F2F4F7')] } },
    ],
    groups: [{ layers: [{ glass: false, 'image-name': 'addo.svg', name: 'addo' }], shadow: { kind: 'none', opacity: 0.5 }, translucency: { enabled: false, value: 0.5 } }],
    'supported-platforms': { squares: 'shared' },
  };
  writeFileSync(join(dir, 'icon.json'), JSON.stringify(doc, null, 2) + '\n');
  written.push(dir);
  if (process.platform !== 'darwin') {
    console.warn('Not on macOS: build/Assets.car and build/icon.icns were left as they were. Rebuild them on a Mac with Xcode 26.');
  } else {
    const work = mkdtempSync(join(tmpdir(), 'app-icon-'));
    try {
      execFileSync('xcrun', ['actool', dir, '--compile', work, '--output-format', 'human-readable-text', '--notices', '--warnings',
        '--output-partial-info-plist', join(work, 'partial.plist'), '--app-icon', 'AppIcon', '--include-all-app-icons',
        '--enable-on-demand-resources', 'NO', '--development-region', 'en', '--target-device', 'mac',
        '--minimum-deployment-target', '26.0', '--platform', 'macosx'], { stdio: ['ignore', 'pipe', 'inherit'] });
      copyFileSync(join(work, 'Assets.car'), join(build, 'Assets.car'));
      written.push(join(build, 'Assets.car'));

      // The .icns for the disk image and macOS before 26, each size drawn for its size.
      const set = join(work, 'icon.iconset');
      mkdirSync(set);
      for (const pt of [16, 32, 128, 256, 512]) {
        writeFileSync(join(set, `icon_${pt}x${pt}.png`), await render('mac', pt));
        writeFileSync(join(set, `icon_${pt}x${pt}@2x.png`), await render('mac', pt * 2));
      }
      execFileSync('iconutil', ['-c', 'icns', set, '-o', join(build, 'icon.icns')]);
      written.push(join(build, 'icon.icns'));
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  }
}

for (const f of written) console.log(f);
