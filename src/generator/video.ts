import type { ProjectState } from '@shared/types';

/**
 * The video player written into a site that shows a video: a small Svelte helper and the address reader it uses.
 * Both are plain, portable source. The reader is the site's copy of src/shared/video.ts (tests keep the two in
 * step); the editor's variant of the helper also stops a playing video when the author returns to Edit, and
 * shows the author why a section has no video yet, a note visitors never get.
 */

export const VIDEO_HELPER_FILE = 'video.js';
export const VIDEO_PLAYER_FILE = 'VideoPlayer.svelte';

/** The address reader, as the site runs it. Mirrors parseVideoUrl, videoEmbedUrl and videoWatchUrl in src/shared/video.ts. */
export const VIDEO_JS = String.raw`// Generated by SiteOrigin Builder. Do not edit: changes are overwritten.
// Reads the address of a single YouTube or Vimeo video and builds its player's address. Nothing else is played.

/** The hosts a video can play from, and where a visitor's browser loads each one's player. */
export const VIDEO_PROVIDERS = {
	youtube: { name: 'YouTube', player: 'https://www.youtube-nocookie.com' },
	vimeo: { name: 'Vimeo', player: 'https://player.vimeo.com' }
};

const MAX_URL = 2048;
const CONTROL = /[\u0000-\u001f\u007f]/;
const YOUTUBE_ID = /^[A-Za-z0-9_-]{11}$/;
const VIMEO_ID = /^\d{1,12}$/;
const VIMEO_HASH = /^[0-9a-f]{6,32}$/i;
const YOUTUBE_HOSTS = ['youtube.com', 'm.youtube.com', 'music.youtube.com', 'youtube-nocookie.com'];
const VIMEO_HOSTS = ['vimeo.com', 'player.vimeo.com'];
const YOUTUBE_ID_PATHS = ['embed', 'shorts', 'live', 'v', 'e'];
const YOUTUBE_NOT_VIDEOS = ['videoseries', 'live_stream'];

/** A start time as the hosts write it ("90", "90s", "1m30s"), in seconds. */
export function parseStart(raw) {
	const v = String(raw ?? '').trim().toLowerCase();
	if (!v) return undefined;
	if (/^\d+$/.test(v)) return safeSeconds(Number(v));
	const m = /^(?:(\d+)h)?(?:(\d+)m)?(?:(\d+)s)?$/.exec(v);
	if (!m || (!m[1] && !m[2] && !m[3])) return undefined;
	return safeSeconds(Number(m[1] ?? 0) * 3600 + Number(m[2] ?? 0) * 60 + Number(m[3] ?? 0));
}

function safeSeconds(n) {
	return Number.isSafeInteger(n) && n > 0 ? n : undefined;
}

function toUrl(raw) {
	let s = raw.trim();
	if (s.startsWith('//')) s = 'https:' + s;
	else if (!/^[a-z][a-z0-9+.-]*:/i.test(s)) s = 'https://' + s;
	try {
		const u = new URL(s);
		if (u.protocol !== 'https:' && u.protocol !== 'http:') return null;
		if (u.username || u.password || u.port) return null;
		return u;
	} catch {
		return null;
	}
}

function youtube(u, host) {
	const parts = u.pathname.split('/').filter(Boolean);
	let id;
	if (host === 'youtu.be') id = parts[0];
	else if (parts[0] === 'watch') id = u.searchParams.get('v') ?? undefined;
	else if (parts.length >= 2 && YOUTUBE_ID_PATHS.includes(parts[0])) id = parts[1];
	if (!id || !YOUTUBE_ID.test(id) || YOUTUBE_NOT_VIDEOS.includes(id)) return null;
	const start = parseStart(u.searchParams.get('t') ?? u.searchParams.get('start'));
	return { provider: 'youtube', id, ...(start ? { start } : {}) };
}

function vimeo(u, host) {
	const parts = u.pathname.split('/').filter(Boolean);
	let id;
	let hash;
	if (host === 'player.vimeo.com') {
		if (parts[0] !== 'video' || parts.length !== 2) return null;
		id = parts[1];
	} else if (parts[0] === 'channels' && parts.length === 3) {
		id = parts[2];
	} else if (parts[0] === 'groups' && parts[2] === 'videos' && parts.length === 4) {
		id = parts[3];
	} else if (parts.length === 1 || parts.length === 2) {
		id = parts[0];
		hash = parts[1];
	}
	hash ??= u.searchParams.get('h') ?? undefined;
	if (!id || !VIMEO_ID.test(id)) return null;
	if (hash !== undefined && !VIMEO_HASH.test(hash)) return null;
	const start = parseStart(/^#t=(.+)$/.exec(u.hash)?.[1]);
	return { provider: 'vimeo', id, ...(hash ? { hash: hash.toLowerCase() } : {}), ...(start ? { start } : {}) };
}

/** The YouTube or Vimeo video an address names, or null for anything else. */
export function parseVideoUrl(raw) {
	if (typeof raw !== 'string' || !raw.trim() || raw.length > MAX_URL || CONTROL.test(raw.trim())) return null;
	const u = toUrl(raw);
	if (!u) return null;
	const host = u.hostname.toLowerCase().replace(/^www\./, '');
	if (host === 'youtu.be' || YOUTUBE_HOSTS.includes(host)) return youtube(u, host);
	if (VIMEO_HOSTS.includes(host)) return vimeo(u, host);
	return null;
}

/** The player's address, built from the parsed parts only. */
export function videoEmbedUrl(source, opts = {}) {
	const params = new URLSearchParams();
	if (source.provider === 'youtube') {
		if (opts.autoplay) params.set('autoplay', '1');
		if (source.start) params.set('start', String(source.start));
		const q = params.toString();
		return VIDEO_PROVIDERS.youtube.player + '/embed/' + source.id + (q ? '?' + q : '');
	}
	if (source.hash) params.set('h', source.hash);
	params.set('dnt', '1');
	if (opts.autoplay) params.set('autoplay', '1');
	return VIDEO_PROVIDERS.vimeo.player + '/video/' + source.id + '?' + params.toString() + (source.start ? '#t=' + source.start + 's' : '');
}

/** The video's own page on its host. */
export function videoWatchUrl(source) {
	if (source.provider === 'youtube') return 'https://www.youtube.com/watch?v=' + source.id + (source.start ? '&t=' + source.start + 's' : '');
	return 'https://vimeo.com/' + source.id + (source.hash ? '/' + source.hash : '') + (source.start ? '#t=' + source.start + 's' : '');
}
`;

/**
 * The player helper. Nothing loads from the video's host until the visitor presses Play: the page shows a button
 * that names the video and the host it plays from, and pressing it adds the host's player, playing, with focus in it.
 * Visitors get nothing for an empty or unsupported address. The editor's variant (`instrument`) shows the author
 * why instead, marked for the bridge to show in Edit and hide in Preview, and drops a playing video on Edit.
 */
export function videoPlayerSvelte(instrument = false): string {
  const editorScript = instrument
    ? `
	// Editor preview only: returning to Edit stops the video and shows its button again, so a click selects the section.
	onMount(() => {
		const html = document.documentElement;
		const sync = () => {
			if (html.hasAttribute('data-so-editing')) playing = '';
		};
		sync();
		const watch = new MutationObserver(sync);
		watch.observe(html, { attributes: true, attributeFilter: ['data-so-editing'] });
		return () => watch.disconnect();
	});`
    : '';
  const empty = instrument
    ? `
{:else}
	<div class={['so-video', 'so-video--empty', className]} data-so-editor-only="">
		<p class="so-video__message">
			{String(url ?? '').trim()
				? 'This address isn’t a single YouTube or Vimeo video, so visitors won’t see a video here. Paste the address of one video.'
				: 'No video yet. Paste the address of a YouTube or Vimeo video in the inspector. Visitors won’t see this box.'}
		</p>
	</div>`
    : '';
  return `<script>
	/**
	 * Plays one YouTube or Vimeo video. Nothing is loaded from the video's host until the visitor presses Play: the
	 * button names the video and the host it plays from, and pressing it adds the host's player, playing, with
	 * keyboard focus inside it. An empty address, or one that is not a supported video, shows nothing.
	 */
	import { ${instrument ? 'onMount, ' : ''}tick } from 'svelte';
	import { VIDEO_PROVIDERS, parseVideoUrl, videoEmbedUrl } from './${VIDEO_HELPER_FILE}';
	import { fill, visitorText } from './visitor-text.js';
	let { url = '', title = '', class: className = '' } = $props();
	// The player's own words, in the language of the page.
	const text = visitorText();
	const video = $derived(parseVideoUrl(url));
	const host = $derived(video ? VIDEO_PROVIDERS[video.provider].name : '');
	const src = $derived(video ? videoEmbedUrl(video, { autoplay: true }) : '');
	// The video's name for screen readers and the player's title; the host's name stands in until it has one.
	const name = $derived((typeof title === 'string' ? title.replace(/\\s+/g, ' ').trim() : '') || fill(text().videoFrom, { host }));
	/** The player address the visitor chose to play: another address shows its own button again. */
	let playing = $state('');
	let frame = $state();
	// A changed address forgets the press, so going back to the first address never plays it unasked.
	$effect.pre(() => {
		if (playing && playing !== src) playing = '';
	});
	async function play() {
		${instrument ? "// Only Preview plays: in Edit, and before the editor has taken over the page, a press selects the section.\n\t\tif (!window.__siteoriginBridge || document.documentElement.hasAttribute('data-so-editing')) return;\n\t\t" : ''}playing = src;
		await tick();
		frame?.focus();
	}${editorScript}
</script>

{#if video}
	<div class={['so-video', className]}>
		{#if playing && playing === src}
			<iframe
				bind:this={frame}
				{src}
				title={name}
				allow="autoplay; encrypted-media; fullscreen; picture-in-picture"
				allowfullscreen
				referrerpolicy="strict-origin-when-cross-origin"
			></iframe>
		{:else}
			<button type="button" class="so-video__play" onclick={play}>
				<svg class="so-video__icon" viewBox="0 0 24 24" aria-hidden="true"><path d="M8 5.5v13l10.5-6.5z" fill="currentColor" /></svg>
				<span class="so-video__label">{text().videoPlay}</span>
				<span class="so-video__title">{name}</span>
				<span class="so-video__note">{fill(text().videoLoads, { host })}</span>
			</button>
		{/if}
	</div>${empty}
{/if}

<style>
	/* A 16:9 frame as wide as its column: the player fills it on every screen size. Until then it grows taller when
	   a long title or large text needs it, so the button's words are never cut off. */
	.so-video {
		position: relative;
		display: grid;
		grid-template-columns: minmax(0, 1fr);
		width: 100%;
		/* A grid or flex row around it never stretches it, and a short flex column never squeezes it. */
		align-self: start;
		min-block-size: min-content;
		overflow: hidden;
		border-radius: var(--so-radius-lg, 0);
		background: #111214;
		color: #ffffff;
	}
	/* Holds the frame's shape in the one cell it shares with the button, which may be taller. */
	.so-video::before {
		content: '';
		grid-area: 1 / 1;
		align-self: start;
		width: 100%;
		aspect-ratio: 16 / 9;
		/* The hosts' players need this much height for their controls on the narrowest phones. */
		min-height: 200px;
	}
	.so-video iframe {
		position: absolute;
		inset: 0;
		width: 100%;
		height: 100%;
		border: 0;
	}
	.so-video__play {
		grid-area: 1 / 1;
		width: 100%;
		min-width: 0;
		border: 0;
		overflow-wrap: anywhere;
		display: flex;
		flex-direction: column;
		align-items: center;
		justify-content: center;
		gap: 0.35rem;
		padding: 1rem;
		background: transparent;
		color: inherit;
		font: inherit;
		text-align: center;
		cursor: pointer;
	}
	.so-video__icon {
		width: 4rem;
		height: 4rem;
		margin-block-end: 0.4rem;
		padding: 1rem;
		border-radius: 50%;
		background: rgba(255, 255, 255, 0.16);
	}
	.so-video__play:hover .so-video__icon {
		background: rgba(255, 255, 255, 0.28);
	}
	.so-video__play:focus-visible {
		outline: 3px solid #ffffff;
		outline-offset: -6px;
	}
	.so-video__label {
		font-weight: 600;
	}
	.so-video__title {
		max-width: 40ch;
	}
	.so-video__note {
		font-size: 0.875em;
		opacity: 0.8;
	}${
    instrument
      ? `
	.so-video--empty {
		background: #f4f4f5;
		color: #3f3f46;
		border: 2px dashed #d97706;
	}
	.so-video__message {
		grid-area: 1 / 1;
		place-self: center;
		padding: 1.5rem;
		max-width: calc(46ch + 3rem);
		overflow-wrap: anywhere;
		text-align: center;
	}`
      : ''
  }
</style>
`;
}

/** A module path that names the player helper, however the path leads to it. */
const NAMES_PLAYER = /['"\`][^'"\`\n]*VideoPlayer(?:\.svelte)?['"\`]/;

/** Whether a component of the site shows a video: its code names the player helper. */
export function usesVideo(state: ProjectState): boolean {
  return Object.values(state.components).some((def) => def.kind === 'code' && typeof def.source === 'string' && NAMES_PLAYER.test(def.source));
}
