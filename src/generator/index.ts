interface EmitCtx {
  state: ProjectState;
  file: string;
  imports: Map<string, string>; // import name -> path
  instrument: boolean;
  /** Definition being emitted, or null for page/shell trees. */
  def: ComponentDefinition | null;
  tree: NodeTree;
  /** Expression (definitions) or literal (pages) giving the identity context. */
  ctxExpr: string;
  /** Names of repeat item variables currently in scope (outermost first). */
  items: string[];
  rctx: ResolveContext;
  indent: number;
}

function useImport(ctx: EmitCtx, name: string, path: string) {
  ctx.imports.set(name, relImport(ctx.file, path));
}

function bindExpr(ctx: EmitCtx, v: unknown, schema?: PropSchema): string {
  if (isBinding(v)) {
    if ('$prop' in v) return safeIdent(v.$prop);
    const itemVar = ctx.items[ctx.items.length - 1] ?? 'item';
    return `${itemVar}.${safeIdent(v.$item)}`;
  }
  return js(schema ? resolveValue(schema, v, ctx.rctx) : v);
}

function safeIdent(name: string): string {
  return /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name) ? name : `_${name.replace(/[^a-zA-Z0-9_]/g, '_')}`;
}

function idAttrs(ctx: EmitCtx, nodeId: string): string {
  if (!ctx.instrument) return '';
  const items = ctx.items.length ? ` data-so-items={[${ctx.items.map((i) => `${i}.id`).join(', ')}].join(',')}` : '';
  const c = ctx.def ? `data-so-ctx={__so}` : `data-so-ctx=${attrJs(ctx.ctxExpr)}`;
  return ` ${c} data-so-node="${nodeId}"${items}`;
}

function classExpr(ctx: EmitCtx, node: GraphNode, extra: string[] = []): string {
  if (ctx.def) {
    const parts = [js(nodeClass(ctx.def, node.id)), ...extra];
    for (const [pid, p] of Object.entries(ctx.def.parts)) if (p.nodeId === node.id) parts.push(`so_o?.[${js(pid)}]`);
    if (node.id === ctx.def.tree?.rootIds[0]) {
      if (ctx.def.variants && Object.keys(ctx.def.variants).length) parts.push(`\`so-${defKey(ctx.def.id)}--\${variant}\``);
      parts.push('className');
    }
    return `{[${parts.join(', ')}]}`;
  }
  const parts = [js(pageNodeClass(node.id)), ...extra];
  return `{[${parts.join(', ')}]}`;
}

function anchorAttr(node: GraphNode): string {
  return node.anchor ? ` id=${attrJs(node.anchor)}` : '';
}

function pad(ctx: EmitCtx): string {
  return '\t'.repeat(ctx.indent);
}

function emitNodes(ctx: EmitCtx, ids: string[]): string {
  return ids.map((id) => emitNode(ctx, id)).filter(Boolean).join('\n');
}

function propSchemaFor(ctx: EmitCtx, v: unknown): PropSchema | undefined {
  if (!ctx.def || !isBinding(v) || !('$prop' in v)) return undefined;
  return ctx.def.properties[v.$prop];
}

function emitNode(ctx: EmitCtx, id: string): string {
  const node = ctx.tree.nodes[id];
  if (!node) return '';
  const p = pad(ctx);
  let out = emitNodeInner(ctx, node);
  if (node.when && ctx.def) {
    useImport(ctx, '{ has }', `${RUNTIME_DIR}/util.js`);
    out = `${p}{#if has(${bindExpr(ctx, node.when)})}\n${indentBlock(out)}\n${p}{/if}`;
  }
  if (node.unless && ctx.def) {
    useImport(ctx, '{ has }', `${RUNTIME_DIR}/util.js`);
    out = `${p}{#if !has(${bindExpr(ctx, node.unless)})}\n${indentBlock(out)}\n${p}{/if}`;
  }
  return out;
}

function indentBlock(s: string): string {
  return s.replace(/^/gm, '\t');
}

function emitNodeInner(ctx: EmitCtx, node: GraphNode): string {
  const p = pad(ctx);
  const ids = idAttrs(ctx, node.id);
  switch (node.kind) {
    case 'element': {
      ctx.indent++;
      const children = emitNodes(ctx, node.children);
      ctx.indent--;
      return `${p}<${node.tag} class=${classExpr(ctx, node)}${anchorAttr(node)}${ids}>${children ? `\n${children}\n${p}` : ''}</${node.tag}>`;
    }
    case 'text': {
      if (node.rich) {
        useImport(ctx, 'SoRichText', `${RUNTIME_DIR}/RichText.svelte`);
        const val = isBinding(node.text) ? bindExpr(ctx, node.text) : js(Array.isArray(node.text) ? node.text : String(node.text).split(/\n{2,}/));
        const listAttr = node.list ? ` list=${js(node.list)}` : '';
        return `${p}<SoRichText paragraphs={${val}}${listAttr} class=${classExpr(ctx, node)}${anchorAttr(node)}${ids} />`;
      }
      const val = isBinding(node.text) ? bindExpr(ctx, node.text) : js(Array.isArray(node.text) ? node.text.join('\n\n') : node.text);
      return `${p}<${node.tag} class=${classExpr(ctx, node)}${anchorAttr(node)}${ids}>{${val}}</${node.tag}>`;
    }
    case 'image': {
      useImport(ctx, 'SoImage', `${RUNTIME_DIR}/Image.svelte`);
      const val = isBinding(node.image) ? bindExpr(ctx, node.image) : js(resolveImage(node.image, ctx.rctx));
      return `${p}<SoImage image={${val}} class=${classExpr(ctx, node)}${anchorAttr(node)}${ids} />`;
    }
    case 'link': {
      useImport(ctx, 'SoLink', `${RUNTIME_DIR}/Link.svelte`);
      const link = isBinding(node.link) ? bindExpr(ctx, node.link) : js(resolveLink(node.link as LinkValue, ctx.rctx));
      const label = bindExpr(ctx, node.label);
      const appearance = bindExpr(ctx, node.appearance);
      return `${p}<SoLink link={${link}} appearance={${appearance}} class=${classExpr(ctx, node)}${anchorAttr(node)}${ids}>{${label}}</SoLink>`;
    }
    case 'icon': {
      useImport(ctx, 'SoIcon', `${RUNTIME_DIR}/Icon.svelte`);
      return `${p}<SoIcon name={${bindExpr(ctx, node.icon)}} class=${classExpr(ctx, node)}${anchorAttr(node)}${ids} />`;
    }
    case 'divider':
      return `${p}<hr class=${classExpr(ctx, node, [js('so-divider')])}${anchorAttr(node)}${ids} />`;
    case 'repeat': {
      const v = `item${ctx.items.length ? ctx.items.length + 1 : ''}`;
      const list = bindExpr(ctx, node.list);
      ctx.items.push(v);
      ctx.indent++;
      const children = emitNodes(ctx, node.children);
      ctx.indent--;
      ctx.items.pop();
      return `${p}{#each ${list} ?? [] as ${v} (${v}.id)}\n${children}\n${p}{/each}`;
    }
    case 'slot':
      return `${p}{@render slot_${safeIdent(node.slot)}?.()}`;
    case 'instance':
      return emitInstance(ctx, node);
  }
}

function emitInstance(ctx: EmitCtx, node: InstanceNode): string {
  const p = pad(ctx);
  const def = ctx.state.components[node.definitionId];
  if (!def) return `${p}<!-- Missing component definition ${node.definitionId} -->`;
  const name = importName(def);
  useImport(ctx, name, defFile(def));
  const attrs: string[] = [];
  // Class: definitions pass their node class; pages pass nothing (overrides use so_o).
  if (ctx.def) attrs.push(`class=${classExpr(ctx, node)}`);
  for (const [propName, schema] of Object.entries(def.properties).sort(([a], [b]) => a.localeCompare(b))) {
    const raw = propName in node.props ? node.props[propName] : schema.default;
    const expr = isBinding(raw) ? bindExpr(ctx, raw) : js(resolveValue(schema, raw, ctx.rctx));
    attrs.push(`${safeIdent(propName)}={${expr}}`);
  }
  const variant = node.variant ?? def.defaultVariant;
  if (variant && def.variants?.[variant]) attrs.push(`variant=${js(variant)}`);
  // Instance overrides at page level are applied through generated override classes.
  if (!ctx.def && node.overrides && Object.keys(node.overrides).length && (def.kind === 'managed' || def.provenance?.forkedFrom)) {
    const map: Record<string, string> = {};
    for (const partId of Object.keys(node.overrides).sort()) map[partId] = overrideClass(node.id, partId);
    attrs.push(`so_o={${js(map)}}`);
  }
  if (ctx.instrument && def.kind === 'managed') {
    const childCtx = ctx.def ? `__so + ${js('|' + node.id)}` : js(`${ctx.ctxExpr}|${node.id}`);
    attrs.push(`__so={${childCtx}}`);
  }
  // Slots
  let slotContent = '';
  if (def.slots) {
    const snippets: string[] = [];
    for (const slotName of Object.keys(def.slots).sort()) {
      const childIds = node.slots?.[slotName] ?? [];
      if (!childIds.length) continue;
      ctx.indent += 2;
      const inner = emitNodes(ctx, childIds);
      ctx.indent -= 2;
      snippets.push(`${p}\t{#snippet slot_${safeIdent(slotName)}()}\n${inner}\n${p}\t{/snippet}`);
    }
    slotContent = snippets.join('\n');
  }
  const open = `${p}<${name}\n${attrs.map((a) => `${p}\t${a}`).join('\n')}\n${p}`;
  let markup = slotContent ? `${open}>\n${slotContent}\n${p}</${name}>` : `${open}/>`;
  if (ctx.instrument && def.kind === 'code') {
    const c = ctx.def ? '{__so}' : attrJs(ctx.ctxExpr);
    markup = `${p}<div style="display: contents" data-so-ctx=${c} data-so-node="${node.id}" data-so-code="true">\n${indentBlock(markup)}\n${p}</div>`;
  }
  return markup;
}

function renderImports(imports: Map<string, string>): string {
  return [...imports.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, path]) => `\timport ${name} from ${js(path)};`)
    .join('\n');
}

