import type { ComponentDefinition, NodeTree, ProjectState } from '@shared/types';
import { isAppearPreset } from '@shared/types';
import { showsPart } from '@shared/page-shell';
import { anchorCapable } from '@engine/tree';

/**
 * Entrances: a section or container with an `appear` preset fades, lifts or scales in the first time it scrolls into
 * view. The markup only names the preset (`data-appear`); a site that uses one also gets a small observer, started by
 * its layout, and the rules below in its site stylesheet. Content is never hidden until the observer arms it, so a
 * page without JavaScript (or before it runs), a printout, a visitor who asks for reduced motion and the editor's
 * Edit mode all show everything as designed. A site without entrances gets none of it.
 */

export const APPEAR_FILE = 'appear.js';

/** The longest stagger, in steps: later items that enter together start with the last of them. */
const MAX_STEP = 4;
const STEP_MS = 90;

/**
 * The rules, appended to site.css. Each one applies only to an element the observer has armed, and only on a screen
 * whose visitor has not asked for reduced motion, so in print and with reduced motion nothing here matches at all.
 * Waiting holds the element transparent with a paused animation of its own (an animation, so no rule of the design
 * can show it early), without moving the box the observer watches; coming in starts the entrance afresh, after its
 * stagger delay. (Delaying the waiting animation itself would send it back to before its start, which ends it.) Lift
 * and scale animate `transform`, which the editor's own shift, scale and turn styles (`translate`, `scale`, `rotate`)
 * never use, so a moved card lands where it was placed. Keyboard focus inside shows an element at once.
 */
export const APPEAR_CSS = `/* Entrances (runtime/${APPEAR_FILE}): only what that script arms, only on screens and without reduced motion. */
@keyframes so-appear-wait { from, to { opacity: 0; } }
@keyframes so-appear-fade { from { opacity: 0; } }
@keyframes so-appear-lift { from { transform: translateY(1.25rem); } }
@keyframes so-appear-scale { from { transform: scale(0.96); } }
@media screen and (prefers-reduced-motion: no-preference) {
  [data-appear][data-appear-state="waiting"]:not(:focus-within) { animation: so-appear-wait 1s paused both; }
  [data-appear][data-appear-state="running"]:not(:focus-within) { animation: so-appear-fade 0.6s cubic-bezier(0.22, 1, 0.36, 1) backwards; }
  [data-appear="lift"][data-appear-state="running"]:not(:focus-within) { animation-name: so-appear-fade, so-appear-lift; }
  [data-appear="scale-subtle"][data-appear-state="running"]:not(:focus-within) { animation-name: so-appear-fade, so-appear-scale; }
${Array.from({ length: MAX_STEP }, (_, i) => `  [data-appear][data-appear-state="running"][data-appear-step="${i + 1}"] { animation-delay: ${(i + 1) * STEP_MS}ms; }`).join('\n')}
}
`;

/**
 * The observer, as plain portable source. The editor's variant (`instrument`) also waits for Preview: in Edit it arms
 * nothing and shows everything, and each return to Preview measures the page afresh, as a visitor arriving would.
 */
export function appearJs(instrument = false): string {
  const active = instrument
    ? `motion.matches && !!window.__siteoriginBridge && !document.documentElement.hasAttribute('data-so-editing')`
    : 'motion.matches';
  const watchMode = instrument
    ? `
	// The editor's Edit mode shows every element as designed; Preview plays the entrances as visitors see them.
	const mode = new MutationObserver(update);
	mode.observe(document.documentElement, { attributes: true, attributeFilter: ['data-so-editing'] });`
    : '';
  return `// Generated by SiteOrigin Builder. Do not edit: changes are overwritten.
/**
 * Entrances: an element marked data-appear (fade, lift or scale-subtle) that is still below the screen when the page
 * starts comes in the first time it scrolls into view. Everything shows without this script, in print and for
 * visitors who ask for reduced motion: the site's stylesheet only animates what this script arms (data-appear-state),
 * and only on screens where motion is welcome. Items of a list marked data-appear-stagger (with the item's ID) that
 * come into view together start one after another.
 */
const PRESETS = ['fade', 'lift', 'scale-subtle'];

/** Starts watching the page, and gives back what stops it. */
export function observeAppear() {
	if (typeof IntersectionObserver !== 'function' || typeof MutationObserver !== 'function' || typeof matchMedia !== 'function') return () => {};
	// The stylesheet keeps printouts whole on its own, so only the visitor's wish for less motion stops this.
	const motion = matchMedia('(prefers-reduced-motion: no-preference)');
	// Every element this script has marked, waiting or coming in, so it can always let go of it, attached or not.
	const marked = new Set();
	let checked = new WeakSet();
	let pending = [];
	let timer = 0;
	let on = false;
	const clear = (el) => {
		marked.delete(el);
		io.unobserve(el);
		el.removeAttribute('data-appear-state');
		el.removeAttribute('data-appear-step');
	};
	const io = new IntersectionObserver((entries) => {
		const entering = entries.filter((e) => e.isIntersecting && marked.has(e.target) && e.target.getAttribute('data-appear-state') === 'waiting').map((e) => e.target);
		entering.sort((a, b) => (a.compareDocumentPosition(b) & Node.DOCUMENT_POSITION_FOLLOWING ? -1 : 1));
		const items = [];
		for (const el of entering) {
			io.unobserve(el);
			// Something inside has keyboard focus: it shows at once.
			if (el.matches(':focus-within')) {
				clear(el);
				continue;
			}
			const item = el.getAttribute('data-appear-stagger');
			if (item !== null && !items.includes(item)) items.push(item);
			const step = item === null ? 0 : Math.min(items.indexOf(item), ${MAX_STEP});
			if (step) el.setAttribute('data-appear-step', String(step));
			el.setAttribute('data-appear-state', 'running');
		}
	});
	// Only what is still below the screen waits: anything a visitor can already see (or has scrolled past) stays.
	// Everything is measured before anything is armed, so the page is laid out once.
	const arm = (els) => {
		const below = els.filter((el) => {
			if (checked.has(el) || !el.isConnected || !PRESETS.includes(el.getAttribute('data-appear'))) return false;
			checked.add(el);
			return el.getClientRects().length > 0 && el.getBoundingClientRect().top >= innerHeight;
		});
		for (const el of below) {
			el.setAttribute('data-appear-state', 'waiting');
			marked.add(el);
			io.observe(el);
		}
	};
	// Content that arrives later (a page a visitor moves to, a section shown later) is measured once the page has
	// been still for a moment: a new page starts at its top (or its anchor), not where the last one was left, and may
	// glide there, starting a few frames later. Until then it shows as it is.
	const quiet = () => {
		clearTimeout(timer);
		timer = setTimeout(() => {
			timer = 0;
			removeEventListener('scroll', quiet);
			const found = pending;
			pending = [];
			if (on) arm(found);
		}, 150);
	};
	const later = (els) => {
		if (!els.length) return;
		pending.push(...els);
		if (!timer) addEventListener('scroll', quiet, { passive: true });
		quiet();
	};
	const within = (root) => (root.nodeType === 1 ? [...(root.matches('[data-appear]') ? [root] : []), ...root.querySelectorAll('[data-appear]')] : []);
	const mo = new MutationObserver((records) => {
		const found = [];
		for (const r of records) {
			if (r.type === 'childList') r.addedNodes.forEach((n) => found.push(...within(n)));
			else if (PRESETS.includes(r.target.getAttribute('data-appear'))) {
				// Changed, or taken away and given back before this saw it: measured afresh unless it is already coming in.
				if (!marked.has(r.target)) checked.delete(r.target);
				found.push(r.target);
			}
			else {
				// A preset taken away lets go at once, and one given back later counts afresh.
				checked.delete(r.target);
				if (marked.has(r.target)) clear(r.target);
			}
		}
		for (const el of marked) if (!el.isConnected) clear(el);
		later(found);
	});
	// An entrance is over when it ends, or when it stops early (the element was hidden).
	const done = (e) => {
		if (e.animationName === 'so-appear-fade' && marked.has(e.target) && e.target.getAttribute('data-appear-state') === 'running') clear(e.target);
	};
	// Keyboard focus moving inside shows it at once, and for good: it never comes in again behind the visitor's back.
	const focused = (e) => {
		for (const el of marked) if (el.contains(e.target)) clear(el);
	};
	const stop = () => {
		on = false;
		mo.disconnect();
		io.disconnect();
		clearTimeout(timer);
		timer = 0;
		removeEventListener('scroll', quiet);
		pending = [];
		for (const el of [...marked]) clear(el);
	};
	const update = () => {
		const want = ${active};
		if (want === on) return;
		if (!want) return stop();
		on = true;
		checked = new WeakSet();
		mo.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['data-appear'] });
		arm(within(document.body));
	};
	motion.addEventListener('change', update);
	document.addEventListener('animationend', done, true);
	document.addEventListener('animationcancel', done, true);
	document.addEventListener('focusin', focused, true);${watchMode}
	update();
	return () => {
		motion.removeEventListener('change', update);
		document.removeEventListener('animationend', done, true);
		document.removeEventListener('animationcancel', done, true);
		document.removeEventListener('focusin', focused, true);${instrument ? '\n\t\tmode.disconnect();' : ''}
		stop();
	};
}
`;
}

/**
 * What a code component's source carries when it may show an entrance, however its author writes it: a preset on its
 * markup, or an entrance it passes to a design inside (any but a written-in `none`).
 */
const CODE_ENTRANCE = /\bdata-appear\s*=|\bso_appear\s*=(?!\s*\{?\s*["'`]none["'`])/;

/**
 * Whether a visitor of the generated site can meet an entrance: one of its pages (drafts included while editing; a
 * published build is generated without them), or the shared header or footer while a page shows it, holds a section
 * or container with a preset, or places a component whose design does, at any depth. A component nothing places, a
 * design's root entrance its only placement turns off (`none`), and a preset on a placement that cannot take one
 * (a code component's) never turn the observer on.
 */
/**
 * The definition that shows a placement's own entrance: its own, or for a design's file converted to code
 * (`generatedFrom`), that design, whose file it is and which took the entrance from its placement.
 */
function entranceTaker(state: ProjectState, defId: string): ComponentDefinition | undefined {
  const def = state.components[defId];
  return def?.kind === 'code' && def.generatedFrom && Object.hasOwn(state.components, def.generatedFrom) ? state.components[def.generatedFrom] : def;
}

export function usesAppear(state: ProjectState): boolean {
  // Each design once for each way it is reached: with its root's own entrance turned off by its placement, or not.
  const seen = new Set<string>();
  const holds = (tree: NodeTree | undefined, rootOff = false): boolean => {
    const rootId = rootOff ? tree?.rootIds[0] : undefined;
    for (const n of Object.values(tree?.nodes ?? {})) {
      if (n.kind === 'element' && isAppearPreset(n.appear) && n.id !== rootId) return true;
      if (n.kind !== 'instance') continue;
      // A design's root takes its placement's choice first.
      const choice = n.id === rootId ? 'none' : n.appear;
      if (isAppearPreset(choice) && anchorCapable(state, entranceTaker(state, n.definitionId))) return true;
      if (placesAppear(n.definitionId, choice === 'none')) return true;
    }
    return false;
  };
  const placesAppear = (defId: string, rootOff: boolean): boolean => {
    const key = `${rootOff ? 'off' : 'on'}:${defId}`;
    if (seen.has(key)) return false;
    seen.add(key);
    const def = state.components[defId];
    if (!def) return false;
    if (def.kind === 'code') return (typeof def.source === 'string' && CODE_ENTRANCE.test(def.source)) || (def.dependencies ?? []).some((d) => placesAppear(d, false));
    return holds(def.tree, rootOff);
  };
  const pages = state.site.pageOrder.filter((id) => Object.hasOwn(state.pages, id)).map((id) => state.pages[id]);
  const shell = (['header', 'footer'] as const).filter((part) => pages.some((p) => showsPart(p, part))).map((part) => state.site.shell[part]);
  return [...pages, ...shell].some((tree) => holds(tree));
}
