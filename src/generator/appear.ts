import type { NodeTree, ProjectState } from '@shared/types';
import { isAppearPreset } from '@shared/types';

/**
 * Entrances: a section or container with an `appear` preset fades, lifts or scales in the first time it scrolls into
 * view. The markup only names the preset (`data-appear`); a site that uses one also gets a small observer, started by
 * its layout, and the rules below in its site stylesheet. Content is never hidden until the observer arms it, so a
 * page without JavaScript (or before it runs), a printout, a visitor who asks for reduced motion and the editor's
 * Edit mode all show everything as designed. A site without entrances gets none of it.
 */

export const APPEAR_FILE = 'appear.js';

/** The longest stagger, in steps: later items that enter together start with the last of them. */
const MAX_STEP = 4;
const STEP_MS = 90;

/**
 * The rules, appended to site.css. Each one applies only to an element the observer has armed, and only on a screen
 * whose visitor has not asked for reduced motion, so in print and with reduced motion nothing here matches at all.
 * Waiting holds the fade at its start (an animation, so no rule of the design can show it early) without moving the
 * box the observer watches. Lift and scale animate `transform`, which the editor's own shift, scale and turn styles
 * (`translate`, `scale`, `rotate`) never use, so a moved card lands where it was placed. Keyboard focus inside shows
 * an element at once.
 */
export const APPEAR_CSS = `/* Entrances (runtime/${APPEAR_FILE}): only what that script arms, only on screens and without reduced motion. */
@keyframes so-appear-fade { from { opacity: 0; } }
@keyframes so-appear-lift { from { transform: translateY(1.25rem); } }
@keyframes so-appear-scale { from { transform: scale(0.96); } }
@media screen and (prefers-reduced-motion: no-preference) {
  [data-appear][data-appear-state]:not(:focus-within) { animation: so-appear-fade 0.6s cubic-bezier(0.22, 1, 0.36, 1) backwards; }
  [data-appear][data-appear-state="waiting"]:not(:focus-within) { animation-play-state: paused; }
  [data-appear="lift"][data-appear-state="running"]:not(:focus-within) { animation-name: so-appear-fade, so-appear-lift; }
  [data-appear="scale-subtle"][data-appear-state="running"]:not(:focus-within) { animation-name: so-appear-fade, so-appear-scale; }
${Array.from({ length: MAX_STEP }, (_, i) => `  [data-appear][data-appear-state="running"][data-appear-step="${i + 1}"] { animation-delay: ${(i + 1) * STEP_MS}ms; }`).join('\n')}
}
`;

/**
 * The observer, as plain portable source. The editor's variant (`instrument`) also waits for Preview: in Edit it arms
 * nothing and shows everything, and each return to Preview measures the page afresh, as a visitor arriving would.
 */
export function appearJs(instrument = false): string {
  const active = instrument
    ? `motion.matches && !!window.__siteoriginBridge && !document.documentElement.hasAttribute('data-so-editing')`
    : 'motion.matches';
  const watchMode = instrument
    ? `
	// The editor's Edit mode shows every element as designed; Preview plays the entrances as visitors see them.
	const mode = new MutationObserver(update);
	mode.observe(document.documentElement, { attributes: true, attributeFilter: ['data-so-editing'] });`
    : '';
  return `// Generated by SiteOrigin Builder. Do not edit: changes are overwritten.
/**
 * Entrances: an element marked data-appear (fade, lift or scale-subtle) that is still below the screen when the page
 * starts comes in the first time it scrolls into view. Everything shows without this script, in print and for
 * visitors who ask for reduced motion: the site's stylesheet only animates what this script arms (data-appear-state),
 * and only on screens where motion is welcome. Items of a list marked data-appear-stagger (with the item's ID) that
 * come into view together start one after another.
 */
const PRESETS = ['fade', 'lift', 'scale-subtle'];

/** Starts watching the page, and gives back what stops it. */
export function observeAppear() {
	if (typeof IntersectionObserver !== 'function' || typeof MutationObserver !== 'function' || typeof matchMedia !== 'function') return () => {};
	const motion = matchMedia('screen and (prefers-reduced-motion: no-preference)');
	const armed = new Set();
	let checked = new WeakSet();
	let on = false;
	const clear = (el) => {
		armed.delete(el);
		el.removeAttribute('data-appear-state');
		el.removeAttribute('data-appear-step');
	};
	const io = new IntersectionObserver((entries) => {
		const entering = entries.filter((e) => e.isIntersecting && armed.has(e.target)).map((e) => e.target);
		entering.sort((a, b) => (a.compareDocumentPosition(b) & Node.DOCUMENT_POSITION_FOLLOWING ? -1 : 1));
		const items = [];
		for (const el of entering) {
			armed.delete(el);
			io.unobserve(el);
			const item = el.getAttribute('data-appear-stagger');
			if (item !== null && !items.includes(item)) items.push(item);
			const step = item === null ? 0 : Math.min(items.indexOf(item), ${MAX_STEP});
			if (step) el.setAttribute('data-appear-step', String(step));
			el.setAttribute('data-appear-state', 'running');
		}
	});
	// Only what is still below the screen waits: anything a visitor can already see (or has scrolled past) stays.
	// Everything is measured before anything is armed, so the page is laid out once.
	const arm = (els) => {
		const below = els.filter((el) => {
			if (checked.has(el) || !PRESETS.includes(el.getAttribute('data-appear'))) return false;
			checked.add(el);
			return el.getClientRects().length > 0 && el.getBoundingClientRect().top >= innerHeight;
		});
		for (const el of below) {
			el.setAttribute('data-appear-state', 'waiting');
			armed.add(el);
			io.observe(el);
		}
	};
	const within = (root) => (root.nodeType === 1 ? [...(root.matches('[data-appear]') ? [root] : []), ...root.querySelectorAll('[data-appear]')] : []);
	// Pages a visitor moves to, and content that shows later, are armed as they arrive.
	const mo = new MutationObserver((records) => {
		const found = [];
		for (const r of records) {
			if (r.type === 'childList') r.addedNodes.forEach((n) => found.push(...within(n)));
			else if (PRESETS.includes(r.target.getAttribute('data-appear'))) found.push(r.target);
			else if (r.target.hasAttribute('data-appear-state')) (io.unobserve(r.target), clear(r.target));
		}
		for (const el of armed) if (!el.isConnected) (io.unobserve(el), clear(el));
		arm(found);
	});
	const done = (e) => {
		if (e.animationName === 'so-appear-fade' && e.target.getAttribute?.('data-appear-state') === 'running') clear(e.target);
	};
	const stop = () => {
		on = false;
		mo.disconnect();
		io.disconnect();
		for (const el of document.querySelectorAll('[data-appear-state]')) clear(el);
	};
	const update = () => {
		const want = ${active};
		if (want === on) return;
		if (!want) return stop();
		on = true;
		checked = new WeakSet();
		mo.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['data-appear'] });
		arm(within(document.body));
	};
	motion.addEventListener('change', update);
	document.addEventListener('animationend', done, true);
	document.addEventListener('animationcancel', done, true);${watchMode}
	update();
	return () => {
		motion.removeEventListener('change', update);
		document.removeEventListener('animationend', done, true);
		document.removeEventListener('animationcancel', done, true);${instrument ? '\n\t\tmode.disconnect();' : ''}
		stop();
	};
}
`;
}

/**
 * Whether a visitor of the generated site can meet an entrance: a page (drafts included while editing; a published
 * build is generated without them), or the shared header or footer, holds a section or container with a preset, or
 * places a component whose design does, at any depth. A component nothing places never turns the observer on, and a
 * placement that turns its design's entrance off (`none`) still counts its design: the cost is a few idle lines.
 */
export function usesAppear(state: ProjectState): boolean {
  const seen = new Set<string>();
  const holds = (tree: NodeTree | undefined): boolean => {
    for (const n of Object.values(tree?.nodes ?? {})) {
      if ((n.kind === 'element' || n.kind === 'instance') && isAppearPreset(n.appear)) return true;
      if (n.kind === 'instance' && placesAppear(n.definitionId)) return true;
    }
    return false;
  };
  const placesAppear = (defId: string): boolean => {
    if (seen.has(defId)) return false;
    seen.add(defId);
    const def = state.components[defId];
    if (!def) return false;
    // A code component (one converted from a design keeps its markup) shows an entrance its source marks, or one of
    // the components it places does.
    if (def.kind === 'code') return (typeof def.source === 'string' && /\bdata-appear\b/.test(def.source)) || (def.dependencies ?? []).some(placesAppear);
    return holds(def.tree);
  };
  return [...Object.values(state.pages), state.site.shell.header, state.site.shell.footer].some(holds);
}
